const { app, dialog } = require('electron');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const assert = require('node:assert/strict');
const { PDFDocument } = require('pdf-lib');
const { createFixtures } = require('./pdf-fixtures.cjs');
const root = path.join(__dirname, '..');
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'localsqueeze-pdf-ui-'));
app.setPath('userData', temp);
const timer = setTimeout(() => { console.error('FAIL PDF UI timeout'); app.exit(1); }, 180000);
app.on('browser-window-created', (_, window) => {
  window.webContents.once('did-finish-load', async () => {
    const run = async code => { try { return await window.webContents.executeJavaScript(code, true); } catch (error) { console.error('Renderer command:', code); throw error; } };
    window.webContents.on('console-message', (_event, _level, message) => { if (message.includes('Error')) console.error(message); });
    const waitFor = async (code, label, attempts = 100) => {
      for (let i = 0; i < attempts; i++) { if (await run(code)) return; await new Promise(resolve => setTimeout(resolve, 100)); }
      throw new Error(`Timeout: ${label}`);
    };
    const clickText = text => run(`Array.from(document.querySelectorAll('button')).find(button=>button.textContent.trim()===${JSON.stringify(text)})?.click(); undefined;`);
    try {
      const { input } = await createFixtures(temp);
      const broken = path.join(temp, 'broken.pdf'); fs.writeFileSync(broken, 'not a PDF');
      const exportDir = path.join(temp, 'exports'); fs.mkdirSync(exportDir);
      dialog.showOpenDialog = async options => ({ canceled: false, filePaths: options.properties.includes('openDirectory') ? [exportDir] : [input, broken] });
      let saveFilters;
      dialog.showSaveDialog = async options => { saveFilters = options.filters; return { canceled: false, filePath: path.join(temp, 'saved.pdf') }; };
      await waitFor('!!window.electron && !!document.querySelector("nav")', 'app ready');
      await run('location.hash="/pdf"; undefined;');
      await waitFor('!!document.querySelector("#pdf-workspace")', 'PDF route');
      assert.equal(await run('document.querySelectorAll("nav > div").length'), 3);
      assert.equal(await run('document.querySelector("input[value=balanced]").checked'), true);
      assert.equal(await run('!!document.querySelector("#pdf-target-size")'), false);
      await clickText('选择 PDF');
      await waitFor('document.querySelectorAll("[data-pdf-id]").length===2', 'native PDF import');
      await clickText('选择 PDF');
      await new Promise(resolve => setTimeout(resolve, 150));
      assert.equal(await run('document.querySelectorAll("[data-pdf-id]").length'), 2, 'duplicate paths ignored');
      await run('document.querySelector("#pdf-compress").click(); undefined;');
      await waitFor('document.querySelector("#pdf-workspace [role=status]").textContent.includes("完成 1 个，失败 1 个")', 'batch results', 600);
      const history = await run('window.stats.getRecentImages(1000)');
      const result = history.images.find(item => item.operation === 'pdf');
      assert.ok(result && fs.existsSync(result.outputPath));
      assert.ok(result.compressedSize < result.originalSize / 2);
      assert.equal((await PDFDocument.load(fs.readFileSync(result.outputPath))).getPageCount(), 2);
      assert.equal((await run('window.stats.getStats()')).stats.totalProcessedImages, 0, 'PDF history must not affect image stats');
      console.log('PASS PDF navigation, native import, duplicate handling, batch continuation, real bytes and separate stats');
      await clickText('另存为');
      await waitFor('document.querySelector("#pdf-workspace [role=status]").textContent.includes("已保存到")', 'save one');
      assert.deepEqual(saveFilters[0].extensions, ['pdf']);
      assert.deepEqual(fs.readFileSync(path.join(temp, 'saved.pdf')), fs.readFileSync(result.outputPath));
      await run('location.hash="/pdf/export"; undefined;');
      await waitFor('document.querySelector("#export-workspace")?.dataset.operation==="pdf" && document.querySelectorAll("[data-image-id]").length===1', 'PDF export');
      await clickText('选择目录');
      await waitFor('!!document.querySelector("input[aria-label=导出目录]").value', 'export directory');
      await run('document.querySelectorAll("#export-workspace input[type=checkbox]")[1].click(); document.querySelector("#export-selected").click(); undefined;');
      await waitFor('document.querySelector("#export-workspace [role=status]").textContent.includes("成功导出 1 个 PDF")', 'batch export');
      assert.deepEqual(fs.readFileSync(path.join(exportDir, result.name)), fs.readFileSync(result.outputPath));
      await run('document.querySelector("#export-selected").click(); undefined;');
      await waitFor('document.querySelector("#export-selected").disabled===false', 'second export');
      assert.equal(fs.readdirSync(exportDir).length, 2, 'same-name export must not overwrite');
      console.log('PASS PDF save dialog, separate export route, byte-exact copy and safe name collision');
      await run('location.hash="/export"; undefined;');
      await waitFor('document.querySelector("#export-workspace")?.dataset.operation==="compression"', 'image export');
      await new Promise(resolve => setTimeout(resolve, 150));
      assert.equal(await run('document.querySelectorAll("[data-image-id]").length'), 0);
      await run('location.hash="/comparison"; undefined;');
      await waitFor('document.querySelector("main").textContent.includes("没有找到可用的压缩结果")', 'comparison excludes PDF');
      await run('location.hash="/pdf"; undefined;');
      await waitFor('document.querySelectorAll("[data-pdf-id]").length===2', 'workspace persists');
      await run(`document.querySelector('input[value=custom]').click(); undefined;`);
      await waitFor(`!!document.querySelector('input[aria-label="PDF 内嵌图片质量"]')`, 'custom quality');
      await run('document.querySelector("#pdf-target-enabled").click(); undefined;');
      await waitFor('!!document.querySelector("#pdf-target-size")', 'optional target');
      await run(`const element=document.querySelector('#pdf-target-size'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(element,'0.01');element.dispatchEvent(new Event('input',{bubbles:true})); undefined;`);
      await clickText('按新设置重新压缩');
      await run('document.querySelector("#pdf-compress").click(); undefined;');
      await waitFor('document.querySelector("#pdf-workspace [role=status]").textContent.includes("完成 1 个，失败 1 个")', 'target batch', 600);
      assert.equal(await run('document.querySelector("#pdf-workspace").textContent.includes("未达到目标")'), true);
      await clickText('清空列表');
      await run(`const transfer=new DataTransfer();transfer.items.add(new File(['broken PDF'], 'dropped.pdf',{type:'application/pdf'}));document.querySelector('#pdf-drop-zone').dispatchEvent(new DragEvent('drop',{bubbles:true,dataTransfer:transfer})); undefined;`);
      await waitFor('document.querySelectorAll("[data-pdf-id]").length===1', 'drop import');
      console.log('PASS preserved workspace, custom settings, unmet target warning and drag import');
      await clickText('清空列表');
      await run(`document.querySelector('input[value=balanced]').click();document.querySelector('#pdf-target-enabled').click(); undefined;`);
      await clickText('选择 PDF');
      await waitFor('document.querySelectorAll("[data-pdf-id]").length===2', 'preview import');
      await run('document.querySelector("#pdf-compress").click(); undefined;');
      await waitFor('document.querySelector("#pdf-workspace [role=status]").textContent.includes("完成 1 个，失败 1 个")', 'preview batch', 600);
      await run('document.querySelector("main").scrollTop=10000; undefined;');
      await new Promise(resolve => setTimeout(resolve, 150));
      assert.equal(await run('document.documentElement.scrollWidth<=innerWidth'), true);
      await window.webContents.capturePage().then(image => fs.writeFileSync(path.join(temp, 'pdf-workspace.png'), image.toPNG()));
      console.log(`PDF UI preview: ${path.join(temp, 'pdf-workspace.png')}`);
      clearTimeout(timer); app.exit(0);
    } catch (error) { console.error(error.stack || error); clearTimeout(timer); app.exit(1); }
  });
});
require(process.env.LOCAL_SQUEEZE_TEST_APP || path.join(root, '.vite/build/main.js'));
